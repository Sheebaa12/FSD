SELECT * FROM Worker WHERE SALARY >= 300000;

-- AND, OR, NOT

SELECT * FROM Worker
WHERE DEPARTMENT = 'HR' AND SALARY > 100000;

SELECT * FROM Worker
WHERE DEPARTMENT = 'Admin' OR DEPARTMENT = 'Account';

SELECT * FROM Worker
WHERE NOT DEPARTMENT = 'HR';

-- IN, BETWEEN, LIKE

SELECT * FROM Worker
WHERE DEPARTMENT IN ('HR', 'Admin', 'Account');

